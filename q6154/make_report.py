def wrapped_list(values, width=16):
    out = ['[']
    for i in range(0, len(values), width):
        row = values[i:i+width]
        suffix = ',' if i+width < len(values) else ''
        out.append('  ' + ', '.join(map(str, row)) + suffix)
    out.append(']')
    return '\n'.join(out)


def wrapped_strings(values, width=12):
    clean = []
    for v in values:
        if '/' in str(v):
            clean.append(str(v))
        else:
            clean.append(str(int(v)))
    return wrapped_list(clean, width)


def wrap_text(s, width=100):
    return '\n'.join(s[i:i+width] for i in range(0, len(s), width))

